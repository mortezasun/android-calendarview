#!/usr/bin/env bash
# Public JVM API guard for the published library artifacts.
#
# The release AARs are built first, then every public class is dumped with javap.
# `./scripts/api-check.sh` fails when the checked-in dumps in api/ differ.
# `./scripts/api-check.sh --update` regenerates them after an intentional API change.
#
# This guard covers public JVM signatures (classes, constructors, methods and fields).
# It does not encode Kotlin default values, annotations, inline-only API or source
# compatibility, so review the dump diff together with the KDoc when updating it.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

UPDATE=0
if [[ $# -gt 0 ]]; then
    if [[ "$1" == "--update" ]]; then
        UPDATE=1
    else
        echo "usage: bash scripts/api-check.sh [--update]" >&2
        exit 2
    fi
fi

if [[ -n "${JAVA_HOME:-}" ]]; then
    JAVAP="$JAVA_HOME/bin/javap"
    JAR="$JAVA_HOME/bin/jar"
else
    JAVAP="$(command -v javap || true)"
    JAR="$(command -v jar || true)"
fi
if [[ ! -x "$JAVAP" || ! -x "$JAR" ]]; then
    echo "javap/jar not found. Set JAVA_HOME to a JDK 17 installation." >&2
    exit 1
fi

MODULES=(library calendar-gregorian calendar-hijri calendar-solarHijri)
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

CLASS_JARS=()
CLASSPATH=""
for module in "${MODULES[@]}"; do
    aar="$module/build/outputs/aar/${module}-release.aar"
    if [[ ! -f "$aar" ]]; then
        echo "Missing $aar." >&2
        echo "Run: ./gradlew :library:assembleRelease :calendar-gregorian:assembleRelease :calendar-hijri:assembleRelease :calendar-solarHijri:assembleRelease" >&2
        exit 1
    fi
    classes_jar="$TMP/${module}.jar"
    unzip -p "$aar" classes.jar > "$classes_jar"
    CLASS_JARS+=("$classes_jar")
    CLASSPATH="${CLASSPATH:+$CLASSPATH:}$classes_jar"
done

mkdir -p "$TMP/api"

for module in "${MODULES[@]}"; do
    classes_jar="$TMP/${module}.jar"
    dump="$TMP/api/${module}.api"
    {
        echo "# Public JVM API of com.github.mortezasun.android-calendarview:${module}"
        echo "# Generated by scripts/api-check.sh; do not edit by hand."
        echo
    } > "$dump"

    while IFS= read -r class; do
        # Internal Kotlin objects are public in JVM bytecode but not public API.
        if [[ "$class" == *"CalendarSelectionSnapshot"* ]]; then
            continue
        fi
        output="$("$JAVAP" -public -classpath "$CLASSPATH" "$class" 2>/dev/null || true)"
        # Package-private classes (private helpers, generated mappings) are not API.
        if ! grep -qE '^public (final |abstract )?(class|interface|enum|@interface)' <<<"$output"; then
            continue
        fi
        # Drop compiler-generated plumbing and Kotlin-internal declarations that are not
        # part of the Kotlin public surface but are public in the JVM bytecode.
        grep -E '^(public |  |\})' <<<"$output" \
            | grep -vE '\$stable|DefaultConstructorMarker|\$default|access\$|synthetic' \
            | grep -vE 'solarHijriMonthTitle' \
            | sed -E 's/([A-Za-z0-9_]+)-[A-Za-z0-9_]+\(/\1(/' \
            >> "$dump"
        printf '\n' >> "$dump"
    done < <(
        "$JAR" tf "$classes_jar" \
            | grep '\.class$' \
            | grep -v '^META-INF/' \
            | sed 's#\.class$##; s#/#.#g' \
            | grep '^com\.develotter\.' \
            | grep -vE '\$[0-9]+' \
            | grep -vE '\$\$' \
            | grep -v 'ComposableSingletons' \
            | grep -v 'WhenMappings' \
            | grep -vE '\.R(\$.*)?$' \
            | grep -vE '\.BuildConfig$' \
            | sort
    )

    # Keep exactly one trailing newline instead of a blank line after the last class.
    content="$(<"$dump")"
    printf '%s\n' "$content" > "$dump"
done

if [[ "$UPDATE" -eq 1 ]]; then
    mkdir -p api
    cp "$TMP"/api/*.api api/
    echo "Updated public API dumps in api/."
    exit 0
fi

FAILED=0
for module in "${MODULES[@]}"; do
    if [[ ! -f "api/${module}.api" ]]; then
        echo "Missing api/${module}.api. Run scripts/api-check.sh --update." >&2
        FAILED=1
        continue
    fi
    if ! diff -u "api/${module}.api" "$TMP/api/${module}.api"; then
        FAILED=1
    fi
done
if [[ "$FAILED" -ne 0 ]]; then
    echo "Public API changed. Review the diff, then run scripts/api-check.sh --update." >&2
    exit 1
fi
echo "Public API matches the checked-in dumps."
