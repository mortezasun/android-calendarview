#!/usr/bin/env bash
# Public JVM API guard for the published library artifacts.
#
# The release AARs are built first, then every public class is dumped with javap.
# `./scripts/api-check.sh` fails when the checked-in dumps in api/ differ.
# `./scripts/api-check.sh --update` regenerates them after an intentional API change.
#
# This guard covers public JVM signatures (classes, constructors, methods and fields). Because the
# shared public API lives in commonMain, these signatures also cover the Kotlin Multiplatform
# surface; iOS-only public declarations would need a separate guard. It does not encode Kotlin
# default values, annotations, inline-only API or source compatibility, so review the dump diff
# together with the KDoc when updating it.
#
# The five platform adapter objects are Kotlin `internal` but appear as public classes in JVM
# bytecode. No binary-compatibility-validator plugin is applied (it creates no tasks with AGP 9's
# built-in Kotlin support), so this script filters those exact implementation classes and then
# rejects them if they ever leak back into a generated dump. The KLIB guard applies the same
# rejection rule.
set -euo pipefail

# Pin the C locale: `sort` orders class names differently under e.g. de_DE, which would rewrite
# every dump on a differently configured host. The checked-in dumps use this collation.
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

UPDATE=0
if [[ $# -gt 0 ]]; then
    if [[ "$1" == "--update" ]]; then
        UPDATE=1
    else
        echo "usage: bash scripts/api-check.sh [--update]" >&2
        exit 2
    fi
fi

if [[ -n "${JAVA_HOME:-}" ]]; then
    JAVAP="$JAVA_HOME/bin/javap"
    JAR="$JAVA_HOME/bin/jar"
else
    JAVAP="$(command -v javap || true)"
    JAR="$(command -v jar || true)"
fi
if [[ ! -x "$JAVAP" || ! -x "$JAR" ]]; then
    echo "javap/jar not found. Set JAVA_HOME to a JDK 17 installation." >&2
    exit 1
fi

MODULES=(library calendar-gregorian calendar-hijri calendar-solarHijri calendar-solarHijri-native calendar-chinese-compose)
# The Kotlin Multiplatform engine publishes a JVM jar instead of an Android AAR.
ENGINE_MODULE=calendar-chinese-native
INTERNAL_PLATFORM_CLASSES='HeatmapPlatformFormatter|GregorianPlatformFormatter|HijriPlatform|SolarHijriPlatform|ChinesePlatform|CalendarLocalePlatform(_.*)?'
# Kotlin does not mangle the names of internal top-level functions (only internal members), so
# they stay public static methods on the file facade class. This one exists for the Gregorian
# overlay tests in :calendar-chinese-compose and is filtered by its exact name.
INTERNAL_TOP_LEVEL_FUNCTIONS='gregorianOverlayData'
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

CLASS_JARS=()
CLASSPATH=""
declare -A JARS
for module in "${MODULES[@]}"; do
    aar="$module/build/outputs/aar/${module}.aar"
    if [[ ! -f "$aar" ]]; then
        echo "Missing $aar." >&2
        echo "Run: ./gradlew :library:publishToMavenLocal :calendar-gregorian:publishToMavenLocal :calendar-hijri:publishToMavenLocal :calendar-solarHijri:publishToMavenLocal :calendar-solarHijri-native:publishToMavenLocal :calendar-chinese-compose:publishToMavenLocal" >&2
        exit 1
    fi
    classes_jar="$TMP/${module}.jar"
    unzip -p "$aar" classes.jar > "$classes_jar"
    JARS[$module]="$classes_jar"
    CLASS_JARS+=("$classes_jar")
    CLASSPATH="${CLASSPATH:+$CLASSPATH:}$classes_jar"
done

VERSION="$(sed -nE 's/^[[:space:]]*version = "([^"]+)"$/\1/p' build.gradle.kts | head -n 1)"
if [[ -z "$VERSION" ]]; then
    echo "Could not read the published version from build.gradle.kts." >&2
    exit 1
fi
ENGINE_LIBS="$ENGINE_MODULE/build/libs"
EXPECTED_ENGINE_JAR="$ENGINE_LIBS/${ENGINE_MODULE}-jvm-${VERSION}.jar"
shopt -s nullglob
ENGINE_JARS=()
for candidate in "$ENGINE_LIBS/${ENGINE_MODULE}-jvm-"*.jar; do
    if [[ "$candidate" == *-sources.jar ]]; then
        continue
    fi
    ENGINE_JARS+=("$candidate")
done
shopt -u nullglob
if [[ ! -f "$EXPECTED_ENGINE_JAR" ]]; then
    echo "Missing exact $ENGINE_MODULE JVM jar: $EXPECTED_ENGINE_JAR" >&2
    echo "Run: ./gradlew :calendar-chinese-native:jvmJar" >&2
    exit 1
fi
if [[ "${#ENGINE_JARS[@]}" -ne 1 || "${ENGINE_JARS[0]}" != "$EXPECTED_ENGINE_JAR" ]]; then
    echo "Ambiguous $ENGINE_MODULE JVM jars; expected exactly $EXPECTED_ENGINE_JAR." >&2
    printf 'Found: %s\n' "${ENGINE_JARS[@]}" >&2
    echo "Remove stale jars from $ENGINE_LIBS (for example with ./gradlew :calendar-chinese-native:clean)." >&2
    exit 1
fi
engine_jar="$EXPECTED_ENGINE_JAR"
JARS[$ENGINE_MODULE]="$engine_jar"
CLASSPATH="${CLASSPATH:+$CLASSPATH:}$engine_jar"

mkdir -p "$TMP/api"

for module in "${MODULES[@]}" "$ENGINE_MODULE"; do
    classes_jar="${JARS[$module]}"
    dump="$TMP/api/${module}.api"
    {
        echo "# Public JVM API of com.github.mortezasun.android-calendarview:${module}"
        echo "# Generated by scripts/api-check.sh; do not edit by hand."
        echo
    } > "$dump"

    while IFS= read -r class; do
        # Internal Kotlin objects are public in JVM bytecode but not public API.
        if [[ "$class" == *"CalendarSelectionSnapshot"* ]]; then
            continue
        fi
        output="$("$JAVAP" -public -classpath "$CLASSPATH" "$class" 2>/dev/null || true)"
        # Package-private classes (private helpers, generated mappings) are not API.
        if ! grep -qE '^public (final |abstract )?(class|interface|enum|@interface)' <<<"$output"; then
            continue
        fi
        # Drop compiler-generated plumbing and Kotlin-internal declarations that are not
        # part of the Kotlin public surface but are public in the JVM bytecode.
        grep -E '^(public |  |\})' <<<"$output" \
            | grep -vE '\$stable|DefaultConstructorMarker|\$default|access\$|synthetic' \
            | grep -vE 'hijriDayCellForEpoch|solarHijriNativeDayCellForEpoch|defaultChineseMonth' \
            | grep -vE "[ .](${INTERNAL_TOP_LEVEL_FUNCTIONS})\\(" \
            | grep -v '\$com_github_mortezasun_' \
            | sed -E 's/([A-Za-z0-9_]+)-[A-Za-z0-9_]+\(/\1(/' \
            >> "$dump"
        printf '\n' >> "$dump"
    done < <(
        "$JAR" tf "$classes_jar" \
            | grep '\.class$' \
            | grep -v '^META-INF/' \
            | sed 's#\.class$##; s#/#.#g' \
            | grep '^com\.develotter\.' \
            | grep -vE '\$[0-9]+' \
            | grep -vE '\$\$' \
            | grep -v 'ComposableSingletons' \
            | grep -v 'WhenMappings' \
            | grep -vE '\.R(\$.*)?$' \
            | grep -vE 'ChineseCalendar(Data|Table)' \
            | grep -vE '\.BuildConfig$' \
            | grep -vE "\.(${INTERNAL_PLATFORM_CLASSES})(\$.*)?$" \
            | sort
    )

    # Keep exactly one trailing newline instead of a blank line after the last class.
    content="$(<"$dump")"
    printf '%s\n' "$content" > "$dump"

    if grep -qE "^public (final )?class .*\.(${INTERNAL_PLATFORM_CLASSES})( |$)" "$dump"; then
        echo "Internal platform adapter leaked into $dump." >&2
        exit 1
    fi
    if grep -qE "[ .](${INTERNAL_TOP_LEVEL_FUNCTIONS})\\(" "$dump"; then
        echo "Internal top-level function leaked into $dump." >&2
        exit 1
    fi
done

if [[ "$UPDATE" -eq 1 ]]; then
    mkdir -p api
    cp "$TMP"/api/*.api api/
    echo "Updated public API dumps in api/."
    exit 0
fi

FAILED=0
for module in "${MODULES[@]}" "$ENGINE_MODULE"; do
    if [[ ! -f "api/${module}.api" ]]; then
        echo "Missing api/${module}.api. Run scripts/api-check.sh --update." >&2
        FAILED=1
        continue
    fi
    if ! diff -u "api/${module}.api" "$TMP/api/${module}.api"; then
        FAILED=1
    fi
done
if [[ "$FAILED" -ne 0 ]]; then
    echo "Public API changed. Review the diff, then run scripts/api-check.sh --update." >&2
    exit 1
fi
echo "Public API matches the checked-in dumps."
